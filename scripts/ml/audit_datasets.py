"""Check which datasets can train which CHM task, and write docs/ml/DATASET_REPORT.md from the real files.

  .venv/Scripts/python scripts/ml/audit_datasets.py

The Telangana files are read and validated here (schema, duplicates, label set, dates, missing values, extract coverage). For the other
datasets only the facts already recorded in datasets/TRAINING-DATA-REGISTER.md and docs/research/ML-TRAINING-REPORT-2026-11.md are
quoted, labelled as such, and the on-disk presence is checked without scanning big folders.
"""
from __future__ import annotations

import csv
from collections import Counter
from datetime import datetime

from ml_common import ROOT, load_config, path, write_json

REQUIRED = ['FarmID', 'category', 'Crop', 'District', 'SDate', 'HDate', 'Season', 'geometry', 'CropCoveredArea']


def telangana() -> dict:
    cfg = load_config('dataset_config')['telangana']
    rows = list(csv.DictReader(open(ROOT / cfg['train_csv'], encoding='utf-8')))
    cols = list(rows[0])
    ids = [r['FarmID'] for r in rows]
    bad_dates = sum(1 for r in rows if not _date(r['SDate']) or not _date(r['HDate']))
    inverted = sum(1 for r in rows if _date(r['SDate']) and _date(r['HDate']) and _date(r['HDate']) <= _date(r['SDate']))
    short = sum(1 for r in rows if _date(r['SDate']) and _date(r['HDate']) and 0 < (_date(r['HDate']) - _date(r['SDate'])).days < 30)
    missing = {c: round(sum(1 for r in rows if r[c] in ('', 'NA', 'nan', None)) / len(rows), 4) for c in cols}
    sample = list(csv.DictReader(open(ROOT / cfg['s2_sample_csv'])))
    prep = path('reports') / 'prepared_data_summary.json'
    from ml_common import read_json
    return {
        'rows': len(rows), 'columns': cols, 'required_columns_present': all(c in cols for c in REQUIRED), 'duplicate_farm_ids': len(ids) - len(set(ids)),
        'labels': dict(Counter(r['category'] for r in rows)), 'crops': dict(Counter(r['Crop'] for r in rows)), 'districts': dict(Counter(r['District'] for r in rows)),
        'seasons': dict(Counter(r['Season'] for r in rows)), 'unparseable_dates': bad_dates, 'harvest_not_after_sowing': inverted, 'season_shorter_than_30_days': short,
        'columns_with_missing_values': {c: v for c, v in missing.items() if v > 0},
        'satellite_extract_fields': len(sample), 'prepared': read_json(prep) if prep.exists() else None,
        'severity_labels_present': any('sever' in c.lower() for c in cols),
    }


def _date(s: str):
    try:
        return datetime.strptime(s.split(' ')[0], '%Y-%m-%d')
    except Exception:
        return None


def other_datasets() -> list[dict]:
    pl = ROOT / '.local/datasets/up/pldd-up'
    af = ROOT / '.local/datasets/agrifieldnet'
    ts_sample = ROOT / 'datasets/TimeSen2Crop'
    return [
        {'name': 'AgriFieldNet India (Radiant Earth, CC-BY-4.0)', 'on_disk': af.exists(), 'target': 'crop type (7,081 fields; 5,551 usable), not health',
         'ml_use': 'excluded from the health models', 'why': 'No stress or health label. The earlier run reached 59.1% accuracy but macro-F1 0.22 (docs/research/ML-TRAINING-REPORT-2026-11.md).', 'source': 'register + earlier report, not re-counted'},
        {'name': 'TimeSen2Crop (Zenodo 4715631, CC BY 4.0)', 'on_disk': ts_sample.exists(), 'target': '16 crop types per pixel, agronomic year 2017-18, EU',
         'ml_use': 'excluded from the health models', 'why': 'Crop-type labels only, per pixel, not India. Bands B1-B9 are present, but there is nothing to predict that is a health or stress outcome.', 'source': 'register; 1,677 sample CSV files are committed under datasets/TimeSen2Crop'},
        {'name': 'PLDD-UP potato leaf photos (CC BY 4.0)', 'on_disk': pl.exists(), 'target': 'leaf image: Healthy / Early Blight / Late Blight (15,519 photos)',
         'ml_use': 'separate image task, not mixed into the satellite models', 'why': 'Photos carry no GPS or date, so they cannot be matched to satellite pixels. Its own report covers it.', 'source': 'register; docs/research/ML-TRAINING-REPORT-2026-11.md'},
    ]


def write_report(t: dict, others: list[dict]) -> str:
    p = t['prepared'] or {}
    lines = [
        '# Dataset compatibility report', '',
        'Generated by `scripts/ml/audit_datasets.py` from the files on this machine. Nothing here is estimated.', '',
        '## What each dataset can and cannot train', '',
        '| Dataset | Target | Use in the CHM health models |', '|---|---|---|',
        f"| Telangana Crop Health Challenge (Zindi / GIZ / ADeX) | Healthy / Pests / Diseased / Stressed per field, one season label | **Used** (only dataset with stress labels) |"]
    for o in others:
        lines.append(f"| {o['name']} | {o['target']} | {o['ml_use']}: {o['why']} |")
    lines += ['', '## Telangana: schema and quality checks', '',
              f"* Rows in Train.csv: **{t['rows']}**; required columns present: **{t['required_columns_present']}**; duplicate FarmIDs: **{t['duplicate_farm_ids']}**.",
              f"* Labels: {t['labels']}. Healthy is {t['labels']['Healthy'] / t['rows']:.1%} of all fields, so accuracy alone is meaningless (always answering Healthy scores that).",
              f"* Unparseable dates: {t['unparseable_dates']}; harvest not after sowing: {t['harvest_not_after_sowing']}; seasons shorter than 30 days: {t['season_shorter_than_30_days']}.",
              f"* Columns with missing values (share): {t['columns_with_missing_values'] or 'none'}.",
              f"* Satellite extract exists for **{t['satellite_extract_fields']}** fields (the rest were never extracted); after the quality rules **{p.get('fields_kept')}** remain "
              f"(dropped: {p.get('dropped')}).",
              f"* Kept fields by label: {p.get('labels')}; by season: {p.get('seasons')}; by sowing year: {p.get('sowing_year')}.",
              f"* Districts (kept): {p.get('districts')}. Seven districts have more than 150 fields; the other seven have {sum(v for k, v in (p.get('districts') or {}).items() if v < 150)} fields in total.",
              f"* Severity labels (Mild / Moderate / Severe) in the dataset: **{t['severity_labels_present']}**.", '',
              '## Consequences for the brief', '',
              '* **Four severity classes cannot be trained.** The labels are cause categories from a survey, not severity. The tasks that can honestly be run are Healthy vs Problem, '
              'Healthy / Pests / Diseased / Stressed, and Pests / Diseased / Stressed among problem fields.',
              '* **Labels are one value per field per season, with no date.** A model cannot learn when stress started, and the labels are survey answers that were not independently verified.',
              f"* **About 99% of fields were sown in 2023** ({p.get('sowing_year')}), so year-held-out validation is impossible. Season-held-out (Rabi to Kharif and back) and district-held-out are the available tests.",
              '* **Not extracted from Earth Engine:** B2, B3, B6, B7, B8A, B12, so **NDWI and EVI cannot be computed**, and soil moisture has no source in the repository. '
              'Only NDVI, NDRE (B8/B5) and NDMI (B8/B11) exist, cloud-masked with SCL classes 0,1,2,3,8,9,10,11. Rebuilding the extract for 3,644 fields is possible but not done here.',
              '* **Licence:** CC-BY-SA 4.0. The register records that the owner accepts share-alike but has not stated whether a model trained on it may ship in the app, so it is used '
              'for evaluation only and no trained weights are shipped or committed (weights stay under `.local/models`).', '',
              '## Other public data', '',
              'No further public dataset with dated, agronomist-confirmed crop-stress labels and severity has been verified for this project, so none is named here and nothing was downloaded. '
              'What is missing is listed in `docs/ml/PRODUCTION_READINESS.md`.', '']
    return '\n'.join(lines)


def main() -> None:
    t, o = telangana(), other_datasets()
    write_json(path('reports') / 'dataset_audit.json', {'telangana': t, 'others': o})
    out = ROOT / 'docs/ml/DATASET_REPORT.md'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(write_report(t, o), encoding='utf-8')
    print(f"audit done: {t['rows']} labelled rows, {t['duplicate_farm_ids']} duplicates, severity labels: {t['severity_labels_present']}")


if __name__ == '__main__':
    main()
